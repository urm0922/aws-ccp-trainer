create table public.questions (
  id text primary key,
  domain text not null,
  prompt text not null,
  explanation text not null,
  correct_choice_id text not null,
  correct_choice_ids text[],
  difficulty text not null default '標準',
  source text,
  reviewed_at date,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.choices (
  id bigint generated by default as identity primary key,
  question_id text not null references public.questions(id) on delete cascade,
  choice_id text not null,
  text text not null,
  explanation text not null,
  unique(question_id, choice_id)
);

create table public.answer_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id text not null references public.questions(id),
  selected_choice_id text not null,
  selected_choice_ids text[],
  is_correct boolean not null,
  session_id text,
  mode text not null default 'practice',
  answered_at timestamptz not null default now()
);

create table public.mock_results (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('mock60', 'mock65')),
  total integer not null,
  correct integer not null,
  duration_seconds integer not null,
  completed_at timestamptz not null default now()
);

create table public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id text not null references public.questions(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, question_id)
);

alter table public.answer_history enable row level security;
alter table public.favorites enable row level security;
alter table public.mock_results enable row level security;
create policy "users read own history" on public.answer_history for select using (auth.uid() = user_id);
create policy "users add own history" on public.answer_history for insert with check (auth.uid() = user_id);
create policy "users manage own favorites" on public.favorites for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage own mock results" on public.mock_results for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
